#!/bin/bash
# Dev-cluster orchestrator for paper evaluation benchmarks.
# Runs the full scenario matrix, scales BentoML for scaleout-3, restores replicas.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
SERVICE="${SERVICE:-sem-classifier}"
NAMESPACE="$SERVICE"
RUN_DATE="$(date -u +%Y-%m-%d)"
RUN_DIR="$PROJECT_DIR/internal_docs/benchmarks/runs/$RUN_DATE"
LATEX_FILE="$PROJECT_DIR/internal_docs/report/benchmark_table.tex"
MASTER_SUMMARY="$PROJECT_DIR/internal_docs/benchmarks/paper_evaluation_2026.json"

if [ -z "${AUTH_CLIENT_SECRET:-}" ] && [ -f "$PROJECT_DIR/services/$SERVICE/secrets.local.yaml" ]; then
    AUTH_CLIENT_SECRET="$(grep 'oidc-client-secret:' "$PROJECT_DIR/services/$SERVICE/secrets.local.yaml" | head -1 | sed 's/.*: "\(.*\)"/\1/')"
    export AUTH_CLIENT_SECRET
fi
[ -n "${AUTH_CLIENT_SECRET:-}" ] || { echo "AUTH_CLIENT_SECRET required" >&2; exit 1; }

mkdir -p "$RUN_DIR"

echo "=== Preflight ==="
curl -fsS http://localhost:8080/health >/dev/null
kubectl get deploy bentoml -n "$NAMESPACE" >/dev/null

run_scenario() {
    local scenario="$1"
    echo ""
    echo "=== Scenario: $scenario ==="
    python3 "$SCRIPT_DIR/benchmark_suite.py" --service "$SERVICE" \
        --scenario "$scenario" \
        --trials 3 \
        --cooldown-s 10 \
        --output text \
        --output-dir "$RUN_DIR/$scenario"
}

echo "=== Baseline (1 replica) ==="
kubectl scale deploy/bentoml --replicas=1 -n "$NAMESPACE"
kubectl rollout status deploy/bentoml -n "$NAMESPACE" --timeout=300s
run_scenario baseline
run_scenario load-5
run_scenario load-10

echo ""
echo "=== Scale-out (3 replicas) ==="
kubectl scale deploy/bentoml --replicas=3 -n "$NAMESPACE"
kubectl rollout status deploy/bentoml -n "$NAMESPACE" --timeout=600s
kubectl get pods -n "$NAMESPACE" -l app.kubernetes.io/name=bentoml
run_scenario scaleout-3

echo ""
echo "=== Restore 1 replica ==="
kubectl scale deploy/bentoml --replicas=1 -n "$NAMESPACE"
kubectl rollout status deploy/bentoml -n "$NAMESPACE" --timeout=300s

python3 - "$RUN_DIR" "$MASTER_SUMMARY" "$LATEX_FILE" <<'PY'
import json
import sys
from pathlib import Path

run_dir = Path(sys.argv[1])
master_path = Path(sys.argv[2])
latex_path = Path(sys.argv[3])

scenarios = ["baseline", "load-5", "load-10", "scaleout-3"]
aggregates = {}
for scenario in scenarios:
    agg_file = run_dir / scenario / "aggregate.json"
    if agg_file.exists():
        aggregates[scenario] = json.loads(agg_file.read_text())

master = {
    "run_date": run_dir.name,
    "scenarios": {name: data.get("aggregate", data) for name, data in aggregates.items()},
    "environment": next(iter(aggregates.values()), {}).get("environment", {}),
}
master_path.write_text(json.dumps(master, indent=2) + "\n", encoding="utf-8")

labels = {
    "baseline": "1 rep, $c{=}1$",
    "load-5": "1 rep, $c{=}5$",
    "load-10": "1 rep, $c{=}10$",
    "scaleout-3": "3 rep, $c{=}10$",
}

def fmt_ci(agg):
    e2e = agg["e2e"]
    p50 = e2e.get("p50")
    lo = e2e.get("ci95_low")
    hi = e2e.get("ci95_high")
    if p50 is None:
        return "n/a"
    if lo is not None and hi is not None:
        return f"{p50:.2f} [{lo:.2f}, {hi:.2f}]"
    return f"{p50:.2f}"

lines = [
    "% Auto-generated by scripts/run_paper_benchmarks.sh",
    "\\begin{tabular}{lrrrr}",
    "\\toprule",
    "Config & Throughput (jobs/min) & E2E p50 [95\\% CI] (s) & Processing p50 (s) & Success \\\\",
    "\\midrule",
]
for scenario in scenarios:
    agg = master["scenarios"].get(scenario)
    if not agg:
        continue
    label = labels[scenario]
    tp = f"{agg['throughput_jobs_per_min']:.1f}"
    e2e = fmt_ci(agg)
    proc = f"{agg['processing']['p50']:.2f}" if agg["processing"].get("p50") is not None else "n/a"
    success = f"{agg['success_rate_pct']:.0f}\\%"
    lines.append(f"{label} & {tp} & {e2e} & {proc} & {success} \\\\")

lines.extend(["\\bottomrule", "\\end{tabular}", ""])
latex_path.parent.mkdir(parents=True, exist_ok=True)
latex_path.write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote {master_path}")
print(f"Wrote {latex_path}")
PY

echo ""
echo "=== Complete ==="
echo "Results: $RUN_DIR"
echo "Master summary: $MASTER_SUMMARY"
echo "LaTeX table: $LATEX_FILE"
